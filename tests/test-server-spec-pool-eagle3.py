#!/usr/bin/env python3
"""EAGLE3 must draft in the per-sequence speculator that llama-server (n_seq = n_parallel) and llama-speculative-simple (n_seq = 1) build.

Row S69-FORK-SERVER-POOL-EAGLE3-DFLASH-IMPLS-2026-10-17-01. Before 2026-10-18, three things each stopped `--spec-type eagle3`:
  1. the pool warned eagle3 "not built" and dropped it, in BOTH tools (speculative-simple also builds the pool, not the
     single-context engine);
  2. a draft converted by this tree's conversion/llama.py did not load: no converter writes eagle3.draft_vocab_size, so the
     output head was expected at the TARGET vocab (151936) and the 32000-row tensor failed check_tensor_dims;
  3. nothing in src/ filled the draft graph's feature input (prepare_eagle3_graph_inputs was lost in the upstream rebase), so a
     draft decode read an input tensor that was never written;
  4. the draft graph built no inp_out_ids, so the first multi-row draft decode with logits on one row aborted on
     GGML_ASSERT(lctx.inp_out_ids && "every model that can must skip unused outputs") (src/llama.cpp set_inputs).

Arms (all CPU, temperature 0, top_k 1):
  PLAIN    llama-server, no speculation, -np 1                     -> reference greedy outputs for P1, P2
  E3       llama-server, -np 2, --spec-type eagle3 -md <draft>,     -> the log names the per-sequence eagle3 impl, no "not built" and
           P1 and P2 concurrently, then P1 again on a reused slot      no feature errors; every request drafts and accepts;
                                                                       outputs == PLAIN (the MTP test's same_greedy, with controls)
  SIMPLE   llama-speculative-simple --spec-type eagle3 -md <draft>  -> n_drafted > 0 and n_accept > 0

Fixtures: LLAMA_TEST_E3_TARGET (default: the Qwen3-8B Q4_K_M gguf in the ollama store) and LLAMA_TEST_E3_DRAFT (default: the
AngelSlim Qwen3-8B EAGLE3 draft converted by this tree, f16). Binary: LLAMA_SERVER_BIN or the first argument (bin dir or exe);
llama-speculative-simple is looked up next to it. Ports: LLAMA_TEST_PORT (default 18940) and the next one. LLAMA_TEST_ARMS = comma
list of plain,e3,simple (default all). Exit 77 = skipped (no binary or no model).
"""

import importlib.util
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("mtp_serving", HERE / "test-server-mtp-serving.py")
mtp = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mtp)

SKIP = 77
# portability-ok: default fixture paths on this host; LLAMA_TEST_E3_TARGET / LLAMA_TEST_E3_DRAFT override them
DEFAULT_TARGET = "models/ollama/blobs/sha256-a3de86cd1c132c822487ededd47a324c50491393e6565cd14bafa40d0b8e686f"
# 2026-11-08: moved out of the engsrv-1018-cpu build tree (reaped) into models/; regenerated by this tree's converter from
# models/hf/qwen3-8b-eagle3 (temp/arex1014/zaudit_1108/_convert_eagle3_1108.cmd).
DEFAULT_DRAFT = "models/gguf/qwen3-8b-eagle3/qwen3-8b-eagle3-f16.gguf"  # portability-ok: see above
N_PREDICT = 32
E3_ARGS = ["--spec-type", "eagle3", "--spec-draft-n-max", "1"]
FEATURE_ERRORS = ("EAGLE3 feature size mismatch", "failed to process speculative batch", "failed to load draft model",
                  "GGML_ASSERT")
# src/llama.cpp prepare_eagle3_graph_inputs logs this for every draft decode that ran with no features once a target is
# attached. The capability probe (common_context_can_seq_rm) is the one expected caller, so at most 1 per log.
ZERO_FEATS = "EAGLE3 draft decode with no target features set"


def main():
    exe = mtp.find_server()
    target = Path(os.environ.get("LLAMA_TEST_E3_TARGET", DEFAULT_TARGET))
    draft = Path(os.environ.get("LLAMA_TEST_E3_DRAFT", DEFAULT_DRAFT))
    arms = set((os.environ.get("LLAMA_TEST_ARMS") or "plain,e3,simple").split(","))
    if exe is None or not target.is_file() or not draft.is_file():
        print("SKIP: server=%s target=%s draft=%s" % (exe, target, draft))
        return SKIP
    simple = exe.parent / ("llama-speculative-simple" + exe.suffix)
    port0 = int(os.environ.get("LLAMA_TEST_PORT", "18940"))
    threads = int(os.environ.get("LLAMA_TEST_THREADS", "4"))
    log_dir = Path(os.environ.get("LLAMA_TEST_LOG_DIR", tempfile.gettempdir()))
    log_dir.mkdir(parents=True, exist_ok=True)
    mtp.N_PREDICT = N_PREDICT
    print("server: %s\ntarget: %s\ndraft : %s\nlogs  : %s\narms  : %s" % (exe, target, draft, log_dir, sorted(arms)))

    fails = 0

    def check(ok, what):
        nonlocal fails
        print(("PASS " if ok else "FAIL ") + what, flush=True)
        if not ok:
            fails += 1

    def run_arm(name, port, extra, body):
        print("\n== %s: %s" % (name, " ".join(extra)), flush=True)
        s = mtp.Server(exe, target, port, extra, log_dir / ("server_e3_%s.log" % name), threads)
        try:
            ready = s.wait_ready()
            check(ready, "%s: server ready (rc %s)" % (name, s.proc.poll()))
            if ready:
                body(s)
        finally:
            s.stop()
        text = s.log_text()
        for ln in mtp.key_lines(text):
            print("   log| " + ln)
        return text

    prompts = {"P1": mtp.P1, "P2": mtp.P2}
    ref = {}

    def check_same(s, arm, k, got):
        ok, note = mtp.same_greedy(s.port, prompts[k], got, ref[k])
        check(ok, "%s %s: output == PLAIN (%s; %s)" % (arm, k, note, got.stats()))
        if not ok:
            print("   %-5s: %r\n   PLAIN: %r" % (arm[:5], got.text[:160], ref[k].text[:160]))

    if arms & {"plain", "e3"}:
        def plain(s):
            for k, p in prompts.items():
                ref[k] = mtp.complete(s.port, p)
                check(len(ref[k].tokens) > 8, "PLAIN %s: generated %d tokens (%s)" % (k, len(ref[k].tokens), ref[k].stats()))
                print("   PLAIN %s: %r" % (k, ref[k].text[:120]))
            if len(ref["P1"].tokens) > 8 and len(ref["P2"].tokens) > 8:
                ok, note = mtp.same_greedy(s.port, mtp.P1, ref["P1"], ref["P1"])
                check(ok, "CONTROL tie check passes PLAIN against itself (%s)" % note)
                fake = mtp.Out()
                fake.tokens = list(ref["P1"].tokens)
                fake.tokens[5] = ref["P2"].tokens[3] if ref["P2"].tokens[3] != fake.tokens[5] else ref["P2"].tokens[4]
                fake.text = "<P1 with token 5 swapped>"
                ok, note = mtp.same_greedy(s.port, mtp.P1, fake, ref["P1"])
                check(not ok, "CONTROL tie check fails PLAIN with token 5 swapped (%s)" % note)

        run_arm("plain", port0, ["-np", "1"], plain)
    have_ref = len(ref) == 2 and all(len(r.tokens) > 8 for r in ref.values())

    if "e3" in arms and have_ref:
        def e3(s):
            outs = mtp.complete_concurrent(s.port, [mtp.P1, mtp.P2])
            for k, got in zip(prompts, outs):
                check(got.draft_n > 0 and got.accepted > 0, "E3 %s (concurrent): drafts verified and accepted (%s)" % (k, got.stats()))
                check_same(s, "E3", k, got)
            again = mtp.complete(s.port, mtp.P1)  # a reused slot: the boundary state must follow the new request
            check(again.draft_n > 0 and again.accepted > 0, "E3 P1 (repeat, reused slot): drafts verified and accepted (%s)" % again.stats())
            check_same(s, "E3-repeat", "P1", again)
            tot = sum(o.draft_n for o in outs + [again])
            acc = sum(o.accepted for o in outs + [again])
            print("   E3 acceptance: %d of %d drafted (%.1f%%)" % (acc, tot, 100.0 * acc / max(1, tot)))

        log = run_arm("e3", port0 + 1, ["-np", "2", "-md", str(draft)] + E3_ARGS, e3)
        check(mtp.STAGE_NOT_BUILT.format("eagle3") not in log, "E3: no 'not built' warning for eagle3")
        check("adding speculative implementation 'eagle3' (per-sequence" in log, "E3: the per-sequence speculator builds eagle3")
        bad = [e for e in FEATURE_ERRORS if e in log]
        check(not bad, "E3: no feature / draft-load errors in the log (%s)" % (bad or "none"))
        n_zero = log.count(ZERO_FEATS)
        check(n_zero <= 1, "E3: draft decodes without features: %d (only the capability probe may)" % n_zero)
    elif "e3" in arms:
        check(False, "E3 arm: no PLAIN reference output")

    if "simple" in arms:
        if not simple.is_file():
            check(False, "SIMPLE: %s not found" % simple)
        else:
            log_path = log_dir / "speculative_simple_e3.log"
            argv = [str(simple), "-m", str(target), "-md", str(draft)] + E3_ARGS + [
                "-t", str(threads), "-c", "1024", "--temp", "0", "-n", str(N_PREDICT), "-p", mtp.P2]
            print("\n== simple: %s" % " ".join(argv[1:]), flush=True)
            with open(log_path, "w", encoding="utf-8", errors="replace") as fh:
                rc = subprocess.run(argv, stdout=fh, stderr=subprocess.STDOUT, timeout=1800,
                                    creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0)).returncode
            text = log_path.read_text(encoding="utf-8", errors="replace")
            m_d = re.search(r"n_drafted\s*=\s*(\d+)", text)
            m_a = re.search(r"n_accept\s*=\s*(\d+)", text)
            n_d = int(m_d.group(1)) if m_d else -1
            n_a = int(m_a.group(1)) if m_a else -1
            for ln in mtp.key_lines(text):
                print("   log| " + ln)
            check(rc == 0, "SIMPLE: llama-speculative-simple exits 0 (rc %d)" % rc)
            check(n_d > 0 and n_a > 0, "SIMPLE: n_drafted %d > 0 and n_accept %d > 0" % (n_d, n_a))
            bad = [e for e in FEATURE_ERRORS if e in text]
            check(not bad, "SIMPLE: no feature / draft-load errors in the log (%s)" % (bad or "none"))
            n_zero = text.count(ZERO_FEATS)
            check(n_zero <= 1, "SIMPLE: draft decodes without features: %d (only a capability probe may)" % n_zero)

    print("\nRESULT: %s (%d failed)" % ("PASS" if fails == 0 else "FAIL", fails))
    return 0 if fails == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
