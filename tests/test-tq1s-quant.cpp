// deterministic input, bit-identical to w13_1017_tq_golden.c
static uint32_t g_s;
static float u01() { g_s = g_s * 1664525u + 1013904223u; return (float)(g_s >> 8) * (1.0f / 16777216.0f); }
static float gauss() { float a = u01(), b = u01(), c = u01(), d = u01(); return ((a + b) + (c + d) - 2.0f) * 1.7320508f; }
static void gen_small(float * x) {
    g_s = 12345u;
    static const float sc[8] = { 0.02f, 0.5f, 1.0f, 3.0f, 1e-3f, 1.0f, 0.0f, 0.01f };
    for (int b = 0; b < 8; ++b) for (int j = 0; j < 32; ++j) x[32*b + j] = gauss() * sc[b];
    for (int j = 0; j < 16; ++j) x[32*5 + j] = 0.0f;
    x[32*7 + 3] = 5.0f;
}
static void gen_big(float * x, int n) { g_s = 777u; for (int i = 0; i < n; ++i) x[i] = gauss() * 0.05f; }
static uint64_t fnv(const void * p, size_t n) { uint64_t h = 1469598103934665603ull; const uint8_t * b = (const uint8_t *) p; for (size_t i = 0; i < n; ++i) { h ^= b[i]; h *= 1099511628211ull; } return h; }

static ggml_type type_by_name(const char * name) {
    for (int t = 0; t < GGML_TYPE_COUNT; ++t) {
        const char * s = ggml_type_name((ggml_type) t);
        if (s && strcmp(s, name) == 0) return (ggml_type) t;
    }
    return GGML_TYPE_COUNT;
}

struct Fmt { const char * name; int want_id; size_t bytes; ggml_type type; };
static Fmt k_fmts[2] = { { "tq3_1s", 74, 16, GGML_TYPE_COUNT }, { "tq4_1s", 75, 20, GGML_TYPE_COUNT } };

static void quant_rows(ggml_type t, const float * x, void * y, int64_t nrows, int64_t n) {
    const auto * tt = ggml_get_type_traits(t);
    for (int64_t r = 0; r < nrows; ++r) tt->from_float_ref(x + r*n, (char *) y + r*ggml_row_size(t, n), n);
}
static void dequant_rows(ggml_type t, const void * y, float * x, int64_t nrows, int64_t n) {
    const auto * tt = ggml_get_type_traits(t);
    for (int64_t r = 0; r < nrows; ++r) tt->to_float((const char *) y + r*ggml_row_size(t, n), x + r*n, n);
}

static bool test_layout() {
    printf("[layout]\n");
    bool all = true;
    for (auto & f : k_fmts) {
        f.type = type_by_name(f.name);
        CHECK(f.type != GGML_TYPE_COUNT, "no ggml type named '%s'", f.name);
        if (f.type == GGML_TYPE_COUNT) { all = false; continue; }
        CHECK((int) f.type == f.want_id, "%s id %d want %d", f.name, (int) f.type, f.want_id);
        CHECK(ggml_blck_size(f.type) == 32, "%s block size %lld", f.name, (long long) ggml_blck_size(f.type));
        CHECK(ggml_type_size(f.type) == f.bytes, "%s type size %zu want %zu", f.name, ggml_type_size(f.type), f.bytes);
        CHECK(ggml_row_size(f.type, 4096) == 4096/32*f.bytes, "%s row size", f.name);
        CHECK(ggml_is_quantized(f.type), "%s is_quantized", f.name);
        const auto * tt = ggml_get_type_traits(f.type);
        CHECK(tt->to_float && tt->from_float_ref, "%s to_float / from_float_ref", f.name);
        CHECK(tt->vec_dot && tt->vec_dot_type == GGML_TYPE_Q8_0, "%s base traits vec_dot vs q8_0", f.name);
        const auto * tc = ggml_get_type_traits_cpu(f.type);
        CHECK(tc && tc->from_float && tc->vec_dot && tc->vec_dot_type == GGML_TYPE_Q8_0, "%s cpu traits row", f.name);
        if (!tt->to_float || !tt->from_float_ref || !tt->vec_dot || !tc || !tc->vec_dot) all = false;
        printf("  %-7s id=%d block=32 size=%zu B (%.2f bpw)\n", f.name, (int) f.type, ggml_type_size(f.type), 8.0*ggml_type_size(f.type)/32);
    }
    return all;
}

static void test_golden() {
    printf("[golden vs their reference]\n");
    float x[256], y[256], yg[256];
    gen_small(x);
    const uint8_t * gold[2] = { k_gold_tq3, k_gold_tq4 };
    for (int fi = 0; fi < 2; ++fi) {
        const Fmt & f = k_fmts[fi];
        std::vector<uint8_t> q(ggml_row_size(f.type, 256));
        quant_rows(f.type, x, q.data(), 1, 256);
        int nbad = 0;
        for (int b = 0; b < 8; ++b) {
            if (memcmp(q.data() + b*f.bytes, gold[fi] + b*f.bytes, f.bytes) != 0) {
                ++nbad;
                printf("  %s block %d differs:", f.name, b);
                for (size_t i = 0; i < f.bytes; ++i) printf(" %02x/%02x", q[b*f.bytes + i], gold[fi][b*f.bytes + i]);
                printf("\n");
            }
        }
        CHECK(nbad == 0, "%s %d of 8 blocks differ from their reference", f.name, nbad);
        dequant_rows(f.type, q.data(), y, 1, 256);
        dequant_rows(f.type, gold[fi], yg, 1, 256);
        CHECK(fnv(y, sizeof y) == k_gold_dq_fnv[fi], "%s dequant(our blocks) float bits differ from their reference (fnv %016llx)", f.name, (unsigned long long) fnv(y, sizeof y));
        CHECK(fnv(yg, sizeof yg) == k_gold_dq_fnv[fi], "%s dequant(THEIR blocks) float bits differ from their reference (fnv %016llx)", f.name, (unsigned long long) fnv(yg, sizeof yg));
        // all-zero block decodes to exact zeros; half-zero block keeps the zero half's scale at 0
        bool zero_ok = true; for (int j = 0; j < 32; ++j) zero_ok = zero_ok && y[32*6 + j] == 0.0f;
        CHECK(zero_ok, "%s all-zero block must decode to zeros", f.name);
        printf("  %-7s 8 blocks byte-identical: %s; dequant bit-identical (ours %d, theirs %d)\n", f.name, nbad ? "NO" : "yes",
               (int)(fnv(y, sizeof y) == k_gold_dq_fnv[fi]), (int)(fnv(yg, sizeof yg) == k_gold_dq_fnv[fi]));
    }
}

static void test_quality() {
    printf("[quality on 65536 gaussian values]\n");
    const int n = 64*1024;
    std::vector<float> x(n), y(n);
    gen_big(x.data(), n);
    for (int fi = 0; fi < 2; ++fi) {
        const Fmt & f = k_fmts[fi];
        std::vector<uint8_t> q(ggml_row_size(f.type, n));
        quant_rows(f.type, x.data(), q.data(), 1, n);
        dequant_rows(f.type, q.data(), y.data(), 1, n);
        double se = 0, ss = 0;
        for (int i = 0; i < n; ++i) { const double d = (double) y[i] - x[i]; se += d*d; ss += (double) x[i]*x[i]; }
        const double nmse = se / ss;
        const uint64_t h = fnv(q.data(), q.size());
        const char * which = h == k_gold_big_fnv[fi][0] ? "matches their contract-on build" : h == k_gold_big_fnv[fi][1] ? "matches their contract-off build" : "matches neither (FMA contraction differs; not checked)";
        printf("  %-7s NMSE %.6f (their reference %.6f); byte hash %016llx %s\n", f.name, nmse, k_gold_nmse[fi], (unsigned long long) h, which);
        CHECK(std::fabs(nmse - k_gold_nmse[fi]) < 0.01 * k_gold_nmse[fi], "%s NMSE %.6f vs their %.6f", f.name, nmse, k_gold_nmse[fi]);
    }
}

static void test_chunk() {
    printf("[ggml_quantize_chunk]\n");
    for (const auto & f : k_fmts) {
        for (int nper : { 32, 96, 4096 }) {
            const int nr = 3;
            std::vector<float> x(nr * nper); g_s = 99u + nper; for (auto & v : x) v = gauss();
            std::vector<uint8_t> a(nr * ggml_row_size(f.type, nper)), b(a.size()), c(a.size());
            std::vector<float> imat(nper); for (int i = 0; i < nper; ++i) imat[i] = 1.0f + (i % 7);
            const size_t got  = ggml_quantize_chunk(f.type, x.data(), a.data(), 0, nr, nper, nullptr, nullptr);
            const size_t got2 = ggml_quantize_chunk(f.type, x.data(), c.data(), 0, nr, nper, imat.data(), nullptr);
            quant_rows(f.type, x.data(), b.data(), nr, nper);
            CHECK(got == a.size() && a == b, "%s nper=%d ggml_quantize_chunk size %zu want %zu / bytes equal %d", f.name, nper, got, a.size(), (int)(a == b));
            CHECK(got2 == a.size() && a == c, "%s nper=%d imatrix changed the bytes (their reference ignores it)", f.name, nper);
            CHECK(ggml_validate_row_data(f.type, a.data(), a.size()), "%s ggml_validate_row_data", f.name);
        }
        printf("  %-7s rows of 32/96/4096: chunk == row quantiser, imatrix ignored, validate ok\n", f.name);
    }
}

static void test_vec_dot() {
    printf("[vec_dot vs dequantise-then-dot]\n");
    const auto * tq8 = ggml_get_type_traits(GGML_TYPE_Q8_0);
    for (const auto & f : k_fmts) {
        double worst = 0;
        for (int nblk : { 1, 2, 3, 7, 16, 64, 128 }) {
            const int n = 32 * nblk;
            std::vector<float> a(n), b(n);
            g_s = 1000u + nblk; for (int i = 0; i < n; ++i) { a[i] = gauss() * 3.0f; b[i] = gauss(); }
            std::vector<uint8_t> qa(ggml_row_size(f.type, n)), qb(ggml_row_size(GGML_TYPE_Q8_0, n));
            quant_rows(f.type, a.data(), qa.data(), 1, n);
            tq8->from_float_ref(b.data(), qb.data(), n);
            std::vector<float> da(n), db(n);
            dequant_rows(f.type, qa.data(), da.data(), 1, n);
            tq8->to_float(qb.data(), db.data(), n);
            double ref = 0, mag = 0;
            for (int i = 0; i < n; ++i) { ref += (double) da[i] * db[i]; mag += std::fabs((double) da[i] * db[i]); }
            float g1 = 0, g2 = 0;
            ggml_get_type_traits(f.type)->vec_dot(n, &g1, 0, qa.data(), 0, qb.data(), 0, 1);
            ggml_get_type_traits_cpu(f.type)->vec_dot(n, &g2, 0, qa.data(), 0, qb.data(), 0, 1);
            CHECK(mag > 1.0, "%s n=%d vacuous dot", f.name, n);
            const double e1 = std::fabs(g1 - ref) / (mag + 1e-30), e2 = std::fabs(g2 - ref) / (mag + 1e-30);
            worst = std::fmax(worst, std::fmax(e1, e2));
            CHECK(e1 < 1e-5 && e2 < 1e-5, "%s n=%d vec_dot base %.7g cpu %.7g vs %.7g", f.name, n, g1, g2, ref);
        }
        printf("  %-7s block counts 1..128: worst |vec_dot - ref| / sum|terms| = %.2e (tol 1e-5)\n", f.name, worst);
    }
}

static void test_graph() {
    printf("[CPU backend MUL_MAT / GET_ROWS]\n");
    ggml_backend_t be = ggml_backend_cpu_init();
    CHECK(be != nullptr, "no cpu backend");
    if (!be) return;
    for (const auto & f : k_fmts) {
        for (int64_t N : { 1, 7, 33 }) {
            const int64_t K = 256, M = 24;
            ggml_init_params ip = { 16u*1024*1024, nullptr, false };
            ggml_context * ctx = ggml_init(ip);
            std::vector<float> w(K * M); g_s = 4242u; for (auto & v : w) v = gauss() * 0.05f;
            ggml_tensor * W = ggml_new_tensor_2d(ctx, f.type, K, M);
            quant_rows(f.type, w.data(), W->data, M, K);
            std::vector<float> wd(K * M);
            dequant_rows(f.type, W->data, wd.data(), M, K);
            ggml_tensor * X = ggml_new_tensor_2d(ctx, GGML_TYPE_F32, K, N);
            for (int64_t i = 0; i < K*N; ++i) ((float *) X->data)[i] = gauss();
            ggml_tensor * Y = ggml_mul_mat(ctx, W, X);
            ggml_tensor * I = ggml_new_tensor_1d(ctx, GGML_TYPE_I32, 3);
            ((int32_t *) I->data)[0] = 5; ((int32_t *) I->data)[1] = 0; ((int32_t *) I->data)[2] = 23;
            ggml_tensor * R = ggml_get_rows(ctx, W, I);
            CHECK(ggml_backend_supports_op(be, Y), "%s MUL_MAT not claimed", f.name);
            CHECK(ggml_backend_supports_op(be, R), "%s GET_ROWS not claimed", f.name);
            ggml_cgraph * gf = ggml_new_graph(ctx);
            ggml_build_forward_expand(gf, Y);
            ggml_build_forward_expand(gf, R);
            CHECK(ggml_backend_graph_compute(be, gf) == GGML_STATUS_SUCCESS, "%s compute", f.name);
            double se = 0, sr = 0;
            for (int64_t j = 0; j < N; ++j) for (int64_t i = 0; i < M; ++i) {
                double s = 0; for (int64_t k = 0; k < K; ++k) s += (double) wd[i*K + k] * ((const float *) X->data)[j*K + k];
                const double d = ((const float *) Y->data)[j*M + i] - s; se += d*d; sr += s*s;
            }
            const double rel = std::sqrt(se / sr);
            CHECK(std::isfinite(rel) && rel < 0.01, "%s MUL_MAT N=%lld rel-rms %.5f", f.name, (long long) N, rel);
            // the weights themselves vs f32: the quantisation error, so MUL_MAT is not trivially agreeing with garbage
            double sew = 0, ssw = 0; for (int64_t i = 0; i < K*M; ++i) { const double d = wd[i] - w[i]; sew += d*d; ssw += (double) w[i]*w[i]; }
            CHECK(sew / ssw < (f.bytes == 16 ? 0.04 : 0.012), "%s weight NMSE %.5f", f.name, sew / ssw);
            bool rows_ok = true;
            for (int r = 0; r < 3; ++r) {
                const int src = ((int32_t *) I->data)[r];
                for (int64_t k = 0; k < K; ++k) rows_ok = rows_ok && ((const float *) R->data)[r*K + k] == wd[src*K + k];
            }
            CHECK(rows_ok, "%s GET_ROWS != dequantised rows", f.name);
            if (N == 7) printf("  %-7s MUL_MAT N=1/7/33 rel-rms vs double(dequant) e.g. %.5f (bound 0.01: Q8_0 activations); GET_ROWS exact; weight NMSE %.5f\n", f.name, rel, sew/ssw);
            ggml_free(ctx);
        }
    }
    ggml_backend_free(be);
}

int main() {
    { ggml_init_params ip = { 1024, nullptr, true }; ggml_free(ggml_init(ip)); }
    ggml_cpu_init();
    if (!test_layout()) {
        printf("test-tq1s-quant: types missing, %d FAILED checks\n", g_fail);
        return 1;
    }
    test_golden();
    test_quality();
    test_chunk();
    test_vec_dot();
    test_graph();
    if (g_fail) { printf("test-tq1s-quant: %d FAILED checks\n", g_fail); return 1; }
    printf("test-tq1s-quant: all checks passed\n");
    return 0;
}
