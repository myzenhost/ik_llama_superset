// TQ3_1S / TQ4_1S weight types (TurboQuant WHT-rotated Lloyd-Max, TheTom/llama-cpp-turboquant ca28b4bc0, MIT).
// Model-free; everything here is synthetic.
//
// WHAT THIS PROVES
//   1. LAYOUT  the two types exist BY NAME ("tq3_1s", "tq4_1s"), at the ids this fork assigned (74 / 75), with 32-element
//              blocks of 16 / 20 bytes (4.0 / 5.0 bpw), is_quantized, to_float + from_float_ref, both CPU dot tables.
//   2. GOLDEN  the reference quantiser reproduces, BYTE FOR BYTE, the blocks THEIR reference code produces for an 8-block
//              vector (gaussian blocks at 6 scales, an all-zero block, a half-zero block, an outlier). The expected bytes were
//              generated by THEIR quantize_row_tq*_1s_ref / dequantize_row_tq*_1s (ggml-turbo-quant.c:671-1018 @ ca28b4bc0)
//              compiled standalone (tmp/w13-1017/w13_1017_tq_golden.c), identical with and without
//              -ffp-contract=off. The dequantiser reproduces their float output bit-exactly (FNV of the float bits), both
//              from our own blocks and from THEIR golden bytes (decoder checked independently of the encoder).
//   3. QUALITY on 65536 gaussian values: NMSE equals their reference's (0.022416 / 0.005268) to 1%. The full byte hash of
//              that run depends on FMA contraction (their own code gives two hashes under two flag sets), so it is printed,
//              not checked.
//   4. CHUNK   ggml_quantize_chunk == the row quantiser for several row lengths, and an imatrix does not change the bytes
//              (their quantize_tq*_1s ignore it: GGML_UNUSED(imatrix)).
//   5. VEC_DOT against Q8_0 equals dequantise-then-dot (double) to fp32 summation tolerance, both trait tables.
//   6. GRAPH   the CPU backend claims and computes MUL_MAT and GET_ROWS on these types and agrees with the dequantised
//              weights. The WHT is per 32-element block and undone inside to_float, so no activation rotation is needed
//              for correctness (their tq_rotate_act / mmvq-tq are a speed path).
// Type lookup is BY NAME at run time, so this file also compiles on a tree without the types and FAILS there.
// It says nothing about GPU backends (none here) or model quality.

