#!/usr/bin/env python3

from glob import glob
import os

TYPES_KV = ["GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0", "GGML_TYPE_IQ4_NL", "GGML_TYPE_Q6_0", "GGML_TYPE_F16"]

SOURCE_FATTN_VEC = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec-f{vkq_size}.cuh"

DECL_FATTN_VEC_F{vkq_size}_CASE({head_size}, {type_k}, {type_v});
"""

SOURCE_FATTN_WMMA_START = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-wmma-f16.cuh"

"""

SOURCE_FATTN_WMMA_CASE = "DECL_FATTN_WMMA_F16_CASE({head_size}, {cols_per_block}, {kq_acc_t});\n"

# --- ported from upstream/unsloth generator (2026-09-07 merge, git show :3:<this path>) ---
# fattn-tile.cuh and mmf.cuh are CLEAN, non-conflicting additions already present in this
# tree (git status: "A", not "AA" -- verified before porting, see dossier evidence). Their
# DECL_FATTN_TILE_CASE / DECL_MMF_CASE macros are confirmed present (13x / 2x, word-boundary
# grep on the resolved single-version file, not the union of an unmerged one). Safe to
# generate against.
HEAD_SIZES_KQ = [40, 64, 72, 80, 96, 112, 128, 192, 256, 320, 512, 576]
HEAD_SIZES_V_OVERRIDE = {576: 512, 320: 256, 192: 128}  # DKQ -> DV override for asymmetric head dims.

SOURCE_FATTN_TILE = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-tile.cuh"

DECL_FATTN_TILE_CASE({head_size_kq}, {head_size_v});
"""

SOURCE_MMF = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmf.cuh"

DECL_MMF_CASE({type});
"""
# --- end ported block ---

TYPES_MMQ = [
    "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0",
    "GGML_TYPE_Q2_K", "GGML_TYPE_Q3_K", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_Q6_K",
    "GGML_TYPE_IQ2_XXS", "GGML_TYPE_IQ2_XS", "GGML_TYPE_IQ2_S", "GGML_TYPE_IQ3_XXS", "GGML_TYPE_IQ3_S",
    "GGML_TYPE_IQ1_S", "GGML_TYPE_IQ1_M", "GGML_TYPE_IQ4_NL", "GGML_TYPE_IQ4_XS", "GGML_TYPE_Q6_0"
]
# NOT ported: theirs' TYPES_MMQ additionally carries GGML_TYPE_Q1_0, GGML_TYPE_Q2_0,
# GGML_TYPE_MXFP4, GGML_TYPE_NVFP4. Withheld because ggml/src/ggml-cuda/mmq.cuh -- the header
# DECL_MMQ_CASE comes from -- is ITSELF an unresolved "AA" conflict in this merge (verified via
# `git status --porcelain` immediately before this edit, not assumed), and mmq.cuh is already
# on file as a FORK-FEATURE+UPSTREAM-ONLY "high-risk" item (fork's MoE-id-routed quantize vs
# theirs' FP4/MXFP4/NVFP4 kernels) requiring its own human merge decision. Porting the type
# list here ahead of that would emit DECL_MMQ_CASE(GGML_TYPE_MXFP4) etc. against a header whose
# real (resolved) content is not yet known -- same coupling risk already flagged for
# fattn-mma-f16.cuh below, not a new one.

SOURCE_MMQ = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmq.cuh"

DECL_MMQ_CASE({type});
"""
# NOT ported: theirs' fattn-mma-f16 generation loop (ncols/ncols2 matrix with per-model niche
# exceptions for MiMo-V2.5/Mistral-Small-4/Gemma4+MTP/DeepSeek/GLM-4.7-Flash). Withheld because
# ggml/src/ggml-cuda/fattn-mma-f16.cuh is ITSELF an unresolved "AA" conflict (verified via
# `git status --porcelain` immediately before this edit) and is already on file as the
# dossier's #1 "FORK-FEATURE extreme, ties to turbo-KV" item -- the fork's hand-tuned
# RTX5090/SM120 kernel vs theirs' portable per-arch dispatch rewrite. Note also: THIS tree's
# generate_cu_files.py, on EITHER side, has never generated the 17 fattn-mma-f16-instance-*.cu
# files that already sit in the escalation set as separately-conflicted checked-in files --
# they are not reproducible by this script as written on either side. That is a drift finding
# for the fattn-mma-f16.cuh/instance-file decision, not something this file can resolve.


def get_short_name(long_quant_name):
    return long_quant_name.replace("GGML_TYPE_", "").lower()


def get_head_sizes(type_k, type_v):
    if type_k == "GGML_TYPE_F16" and type_v == "GGML_TYPE_F16":
        return [64, 128, 256]
    if type_k == "GGML_TYPE_F16":
        return [64, 128]
    return [128]


# DELETE ONLY WHAT THIS SCRIPT OWNS.
#
# This loop used to be `for filename in glob("*.cu"): os.remove(filename)` -- it wiped the
# WHOLE directory and then rewrote only the combinations TYPES_KV and TYPES_MMQ produce.
# MEASURED 2026-08-23 on this tree: 275 .cu files live here, and 18 of them are HAND-WRITTEN
# and cannot be regenerated by anything below --
#   14 fattn-vec turbo instances (the TurboQuant KV matrix; TYPES_KV names no turbo type)
#    4 g128 instances: mmq/mmvq for q1_0_g128 and q2_0_g128 (TYPES_MMQ names no g128 type)
# A single run therefore destroyed all 18 with no error and no trace, and the build silently
# lost g128 prefill and TurboQuant KV attention. Two of those files were written the same day.
#
# theirs' generate_cu_files.py (upstream/unsloth side of this merge, git show :3:<this path>)
# STILL does the bare `for filename in glob("*.cu"): os.remove(filename)` with no guard --
# confirmed by direct read of that stage, not inferred -- so taking it wholesale reproduces
# this exact incident. Resolution: this file stays ours' guarded delete loop; theirs' new
# generation coverage is ported piecemeal above, gated on each dependency header's OWN merge
# state, never on taking this file's delete loop from theirs.
#
# Ownership is decided by the marker this script itself stamps into every file it writes, so
# the test cannot drift from the behaviour: a file carrying that line is ours and is replaced;
# anything else is left alone. The kept count is PRINTED, because a silent cleanup is how the
# original loop stayed invisible.
AUTOGEN_MARK = "autogenerated by generate_cu_files.py"

_removed, _kept = 0, []
for filename in glob("*.cu"):
    try:
        with open(filename, encoding="utf-8", errors="replace") as _f:
            _head = _f.read(400)
    except OSError:
        _kept.append(filename)      # unreadable is NOT ours to delete
        continue
    if AUTOGEN_MARK in _head:
        os.remove(filename)
        _removed += 1
    else:
        _kept.append(filename)
print("regenerating: removed %d autogenerated file(s), kept %d hand-written file(s)"
      % (_removed, len(_kept)))
if _kept:
    print("  kept: %s" % ", ".join(sorted(_kept)[:24]))

for vkq_size in [16, 32]:
    for type_k in TYPES_KV:
        for type_v in TYPES_KV:
            for head_size in get_head_sizes(type_k, type_v):
                with open(f"fattn-vec-f{vkq_size}-instance-hs{head_size}-{get_short_name(type_k)}-{get_short_name(type_v)}.cu", "w") as f:
                    f.write(SOURCE_FATTN_VEC.format(vkq_size=vkq_size, head_size=head_size, type_k=type_k, type_v=type_v))

for kq_acc_t in ["half", "float"]:
    for cols_per_block in [8, 16, 32]:
        if kq_acc_t == "float" and cols_per_block == 8:
            continue

        with open(f"fattn-wmma-f16-instance-kq{kq_acc_t}-cpb{cols_per_block}.cu", "w") as f:
            f.write(SOURCE_FATTN_WMMA_START)

            for head_size in [64, 80, 96, 112, 128, 256]:
                if cols_per_block == 8 and head_size % 32 != 0: # wmma fragment is 8x32
                    continue
                if kq_acc_t == "float" and cols_per_block == 32 and head_size == 256: # register spilling, bad performance
                    continue
                f.write(SOURCE_FATTN_WMMA_CASE.format(kq_acc_t=kq_acc_t, cols_per_block=cols_per_block, head_size=head_size))

for type in TYPES_MMQ:
    with open(f"mmq-instance-{get_short_name(type)}.cu", "w") as f:
        f.write(SOURCE_MMQ.format(type=type))

# --- ported generation loops (see headers above for why these two and not the others) ---
for head_size_kq in HEAD_SIZES_KQ:
    head_size_v = HEAD_SIZES_V_OVERRIDE.get(head_size_kq, head_size_kq)
    with open(f"fattn-tile-instance-dkq{head_size_kq}-dv{head_size_v}.cu", "w") as f:
        f.write(SOURCE_FATTN_TILE.format(head_size_kq=head_size_kq, head_size_v=head_size_v))

for type in range(1, 17):
    with open(f"mmf-instance-ncols_{type}.cu", "w") as f:
        f.write(SOURCE_MMF.format(type=type))
